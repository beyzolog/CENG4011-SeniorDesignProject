    print(f"📊 Extracted Diverse Clusters : {len(cluster_df):,}")
    print(f"🧬 Average Group Density Size : {cluster_df['Cluster_Size'].mean():.1f} structures/cluster")
    print("="*80)
    print(f"\n✅ All structures are verified and ready for molecular docking tests!")
    print(f"   Destination File: {os.path.join(WORK_DIR, final_output)}")

