def run_step2():
    # Context switch execution domain into the dynamic predictions path
    os.chdir(WORK_DIR)
    
    print("="*80)
    print(f" {GENE_NAME} ({exp_suffix.upper()}) - BIO-CHEMICAL REFINERY & LEAD SELECTION")
    print("="*80)
    
    stats = FilteringStats()
    
    try:
        df = pd.read_csv(INPUT_FILE)
        initial_count = len(df)
        print(f"\n Loading prefitered pool: {INPUT_FILE}")
        print(f" Starting size: {initial_count:,} molecules")
        stats.add_stage("Başlangıç (Step 1 çıktısı)", initial_count, 100.0, 
                       df['prediction_score'].mean(), "Hızlı filtreler uygulanmış")
    except FileNotFoundError:
        print(f" CRITICAL ERROR: compiled pool target file '{INPUT_FILE}' not found.")
        print("   Please execute 06_combine_and_prefilter.py before running this refinery.")
        return
    
    print("\n" + "="*80)
    print("AŞAMA 1: PAINS VE BRENK TOKSİSİTE SEÇİMLERİ")
    print("="*80)
    
    params = FilterCatalogParams()
    params.AddCatalog(FilterCatalogParams.FilterCatalogs.PAINS)
    params.AddCatalog(FilterCatalogParams.FilterCatalogs.BRENK)
    catalog = FilterCatalog(params)
    
    print(" Scanning structures for toxicophoric patterns...")
    start_time = time.time()
    df['pains_passed'] = df['Canonical_SMILES'].apply(lambda x: check_pains_brenk(x, catalog))
    df = df[df['pains_passed'] == True].drop('pains_passed', axis=1)
    elapsed = time.time() - start_time
    
    after_pains = len(df)
    print(f" Toxicophore elimination finished ({elapsed:.1f}s)")
    print(f"   Safe structures remaining: {after_pains:,} ({after_pains/initial_count*100:.1f}%)")
    stats.add_stage("PAINS/Brenk Filtresi", after_pains, after_pains/initial_count*100,
                   df['prediction_score'].mean(), "Problematik yapılar elendi")
    
    print("\n" + "="*80)
    print("AŞAMA 2: HESAPLAMA OPTİMİZASYONU SINIRLAMASI (Top 50,000)")
    print("="*80)
    
    if len(df) > 50000:
        df = df.nlargest(50000, 'prediction_score')
        print(f" Truncated pool to top 50,000 structures to optimize clustering runtime.")
        print(f"   Probability Range: {df['prediction_score'].min():.4f} - {df['prediction_score'].max():.4f}")
    else:
        print(f"  Pool size safely under runtime thresholds ({len(df):,})")
    
    after_top_selection = len(df)
    stats.add_stage("Top 50K Seçimi", after_top_selection, after_top_selection/initial_count*100,
                   df['prediction_score'].mean(), "Hesaplama optimizasyonu")
    
    print("\n" + "="*80)
    print("AŞAMA 3: LIPINSKI RULE OF 5 VALIDATION (Max 2 Violations)")
    print("="*80)
    
    print(" Evaluating drug-likeness boundary violations...")
    df['lipinski_violations'] = df['Canonical_SMILES'].apply(calculate_lipinski_violations)
    df = df[df['lipinski_violations'] <= MAX_LIPINSKI_VIOLATIONS]
    
    after_lipinski = len(df)
    print(f"✅ Lipinski Ro5 compliance verified.")
    print(f"   Compliant structures remaining: {after_lipinski:,} ({after_lipinski/initial_count*100:.1f}%)")
    
    violation_counts = df['lipinski_violations'].value_counts().sort_index()
    for v, count in violation_counts.items():
        print(f"   {v} ihlal: {count:,} molekül")
    
    stats.add_stage("Lipinski Filtresi (≤2 ihlal)", after_lipinski, after_lipinski/initial_count*100,
                   df['prediction_score'].mean(), f"İhlal dağılımı kaydedildi")
    
    print("\n" + "="*80)
    print("AŞAMA 4: ADANCED DRUGLIKENESS CRITERIA (Veber Parameters)")
    print("="*80)
    
    print("⏳ Scanning TPSA, FractionCSP3, and rotatable bonds properties...")
    df['detailed_druglike'] = df['Canonical_SMILES'].apply(check_detailed_druglikeness)
    df = df[df['detailed_druglike'] == True].drop('detailed_druglike', axis=1)
    
    after_detailed = len(df)
    print(f"✅ Rigid parameter filters completed.")
    print(f"   Purified structures remaining: {after_detailed:,} ({after_detailed/initial_count*100:.1f}%)")
    stats.add_stage("Veber + Yapısal Kalite", after_detailed, after_detailed/initial_count*100,
                   df['prediction_score'].mean(), "TPSA, Fsp3, aromatik halka kontrolleri")
    
    print("\n" + "="*80)
    print("AŞAMA 5: NON-REDUNDANT STRUCTURAL DIVERSITY MINING")
    print("="*80)
    
    final_df, cluster_df = diversity_clustering(df, TARGET_MOLECULES, TANIMOTO_THRESHOLD)
    final_count = len(final_df)
    
    stats.add_stage("Diversity Clustering", final_count, final_count/initial_count*100,
                   final_df['prediction_score'].mean(), 
                   f"Tanimoto {TANIMOTO_THRESHOLD}, {len(cluster_df)} cluster")
    
    print("\n" + "="*80)
    print("EXPORTING ARTIFACTS TO EXPERIMENT DIRECTORY")
    print("="*80)
    
    # Construct completely dynamic output destinations
    final_output = f"{GENE_NAME.lower()}_{exp_suffix}_final_1000.csv"
    cluster_output = f"{GENE_NAME.lower()}_{exp_suffix}_clusters.csv"
    report_output = f"{GENE_NAME.lower()}_{exp_suffix}_filtering_report.txt"
    
    final_df_clean = final_df.drop('lipinski_violations', axis=1, errors='ignore')
    final_df_clean.to_csv(final_output, index=False)
    print(f"✅ Lead file exported: {final_output} ({len(final_df_clean):,} unique compounds)")
    
    cluster_df.to_csv(cluster_output, index=False)
    print(f"✅ Cluster metadata exported: {cluster_output} ({len(cluster_df):,} groups mapped)")
    
    stats.save_report(report_output)
    print(f"✅ Rapor dosyası dışa aktarıldı: {report_output}")
    
