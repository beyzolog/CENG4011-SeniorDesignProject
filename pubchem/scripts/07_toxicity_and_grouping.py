class FilteringStats:
    """Tracks and logs filtration step reductions dynamically"""
    def __init__(self):
        self.stages = []
    
    def add_stage(self, stage_name, count, percentage, avg_score=None, notes=""):
        self.stages.append({
            'stage': stage_name,
            'count': count,
            'percentage': percentage,
            'avg_score': avg_score,
            'notes': notes
        })
    
    def save_report(self, filename):
        with open(filename, 'w') as f:
            f.write("="*80 + "\n")
            f.write(f"{GENE_NAME} {exp_suffix.upper()} REFINERY & FILTRATION REPORT\n")
            f.write("="*80 + "\n\n")
            
            for i, stage in enumerate(self.stages, 1):
                f.write(f"AŞAMA {i}: {stage['stage']}\n")
                f.write(f"  Kalan Molekül: {stage['count']:,}\n")
                f.write(f"  Yüzde: {stage['percentage']:.2f}%\n")
                if stage['avg_score']:
                    f.write(f"  Ortalama Skor: {stage['avg_score']:.4f}\n")
                if stage['notes']:
                    f.write(f"  Not: {stage['notes']}\n")
                f.write("\n")
            
            f.write("="*80 + "\n")
            f.write(f"FİNAL SONUÇ: {self.stages[-1]['count']:,} Molekül (Docking Ready)\n")
            f.write("="*80 + "\n")

