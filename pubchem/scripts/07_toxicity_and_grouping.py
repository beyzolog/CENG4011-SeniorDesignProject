# DIVERSITY CLUSTERING (TANIMOTO MINING ENGINE)
# ============================================================================

def diversity_clustering(df, target_count, similarity_threshold):
    print(f"\n🧬 Diversity Clustering Engine Initialized...")
    print(f"   Target Limit: {target_count} Leaders | Similarity Ceiling: Tanimoto {similarity_threshold}")
    
    df_sorted = df.sort_values(by="prediction_score", ascending=False).reset_index(drop=True)
    
    print(" Computing Morgan fingerprints (Radius=2, 2048-bit)...")
    mols = []
    valid_indices = []
    for idx, smiles in enumerate(df_sorted['Canonical_SMILES']):
        mol = Chem.MolFromSmiles(smiles)
        if mol is not None:
            mols.append(mol)
            valid_indices.append(idx)
    
    df_sorted = df_sorted.iloc[valid_indices].reset_index(drop=True)
    fps = [AllChem.GetMorganFingerprintAsBitVect(m, 2, nBits=2048) for m in mols]
    
    print(f" {len(fps):,} structures converted to bit arrays successfully.")
    
    selected_indices = []
    remaining = list(range(len(df_sorted)))
    cluster_info = []
    
    print(" Executing non-redundant scaffold clustering isolation...")
    
    while len(selected_indices) < target_count and remaining:
        current = remaining.pop(0)
        selected_indices.append(current)
        
        group_members = [current]
        to_remove = []
        
        for i in remaining:
            sim = DataStructs.TanimotoSimilarity(fps[current], fps[i])
            if sim >= similarity_threshold:
                group_members.append(i)
                to_remove.append(i)
        
        for r in to_remove:
            remaining.remove(r)
        
        members_df = df_sorted.iloc[group_members]
        cluster_info.append({
            "Cluster_ID": len(selected_indices),
            "Representative_CID": df_sorted.iloc[current]['CID'],
            "Representative_Score": df_sorted.iloc[current]['prediction_score'],
            "Cluster_Size": len(group_members),
            "Member_CIDs": members_df['CID'].tolist(),
            "Avg_Similarity": np.mean([DataStructs.TanimotoSimilarity(fps[current], fps[i]) for i in group_members])
        })
        
        if len(selected_indices) % 100 == 0:
            print(f"   ✓ Selected {len(selected_indices)} unique cluster heads...")
    
    print(f" Structural mining finished: {len(selected_indices)} diverse leads selected.")
    
    final_df = df_sorted.iloc[selected_indices].copy()
    cluster_df = pd.DataFrame(cluster_info)
    
    return final_df, cluster_df

