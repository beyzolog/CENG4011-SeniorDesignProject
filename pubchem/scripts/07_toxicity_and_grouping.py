def check_pains_brenk(smiles, catalog):
    """PAINS and Brenk toxicophore filtration"""
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return False
        return not catalog.HasMatch(mol)
    except:
        return False

def calculate_lipinski_violations(smiles):
    """Calculates Lipinski Rule of 5 violations counts"""
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return 999
        
        violations = 0
        if Descriptors.MolWt(mol) > 500: violations += 1
        if Descriptors.MolLogP(mol) > 5: violations += 1
        if Descriptors.NumHDonors(mol) > 5: violations += 1
        if Descriptors.NumHAcceptors(mol) > 10: violations += 1
        return violations
    except:
        return 999

def check_detailed_druglikeness(smiles):
    """Detailed druglikeness filters (Veber constraints + structural quality)"""
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return False
        
        tpsa = Descriptors.TPSA(mol)
        if tpsa < 60 or tpsa > 140: return False
        
        n_rot = Descriptors.NumRotatableBonds(mol)
        if n_rot > 15: return False
        
        fsp3 = Descriptors.FractionCSP3(mol)
        if fsp3 < 0.2: return False
        
        aromatic_rings = Descriptors.NumAromaticRings(mol)
        if aromatic_rings > 4: return False
        
        formal_charge = Chem.rdmolops.GetFormalCharge(mol)
        if abs(formal_charge) > 1: return False
        
        return True
    except:
        return False

